// v1.3.0 — baton gate: CI-facing exit gate (Stage 5 Reach).
//
// Runs the four read-only health checks and exits nonzero if the repo is not
// in a trustworthy state. Designed to run in GitHub Actions on every PR:
//
//   1. doctor        — structural integrity (errors fail)
//   2. stale dry-run — new staleness since last verify
//   3. conflicts     — unacknowledged conflicts fail
//   4. done preview  — tasks stuck in non-terminal states are reported
//                      (fails only with --strict-done)
//
// `baton gate --init` writes .github/workflows/baton-gate.yml so the repo
// self-instruments its own CI in one command.

import { writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { doctor } from './doctor.js';
import { stale } from './stale.js';
import { conflicts } from './conflicts.js';
import { replay } from '../core/ledger-replay.js';
import { readLedger } from '../io/ledger-file.js';

export interface GateCheck {
  name: string;
  pass: boolean;
  detail: string;
}

export interface GateResult {
  pass: boolean;
  checks: GateCheck[];
}

export async function gate(
  repoRoot: string,
  opts: { strictDone?: boolean } = {},
): Promise<GateResult> {
  const checks: GateCheck[] = [];

  // 1. doctor
  const doctorResult = await doctor(repoRoot);
  const doctorErrors = doctorResult.findings.filter(f => f.level === 'error');
  checks.push({
    name: 'doctor',
    pass: !doctorResult.hasErrors,
    detail: doctorErrors.length === 0
      ? `ok (${doctorResult.findings.filter(f => f.level === 'warning').length} warnings)`
      : doctorErrors.map(e => e.code).join(', '),
  });

  // 2. stale (dry-run)
  let staleCount = -1;
  let staleDetail = 'skipped';
  try {
    const staleResult = await stale(repoRoot, { dryRun: true });
    staleCount = staleResult.staleClaims.length;
    staleDetail = `${staleResult.totalChecked} checked, ${staleCount} stale`;
  } catch (e) {
    staleDetail = `error: ${(e as Error).message.slice(0, 120)}`;
  }
  checks.push({ name: 'stale', pass: staleCount === 0, detail: staleDetail });

  // 3. conflicts
  let conflictCount = -1;
  let conflictDetail = 'skipped';
  try {
    const c = await conflicts(repoRoot, {});
    conflictCount = [
      ...c.decisionConflicts.filter(x => !x.acknowledged),
      ...c.claimConflicts.filter(x => !x.acknowledged),
    ].length;
    conflictDetail = conflictCount === 0 ? 'ok' : `${conflictCount} unacknowledged`;
  } catch (e) {
    conflictDetail = `error: ${(e as Error).message.slice(0, 120)}`;
  }
  checks.push({ name: 'conflicts', pass: conflictCount === 0, detail: conflictDetail });

  // 4. task flow (non-strict: only fails on blocked or needs_work tasks)
  let taskDetail = 'no tasks';
  let taskPass = true;
  try {
    const { events } = await readLedger(repoRoot);
    const state = replay(events);
    const stuck: string[] = [];
    for (const [taskId, t] of state.tasks) {
      if (t.status === 'blocked') stuck.push(`${taskId} blocked`);
      else if (t.status === 'needs_work') stuck.push(`${taskId} needs_work`);
    }
    taskPass = stuck.length === 0;
    taskDetail = stuck.length === 0
      ? `${state.tasks.size} task(s) flowing`
      : stuck.join(', ');
  } catch (e) {
    taskPass = false;
    taskDetail = `error: ${(e as Error).message.slice(0, 120)}`;
  }
  checks.push({ name: 'tasks', pass: taskPass, detail: taskDetail });

  // strict-done: every task must be terminal-done (uses baton done gates)
  if (opts.strictDone) {
    const { done } = await import('./done.js');
    const doneResult = await done(repoRoot);
    checks.push({
      name: 'done',
      pass: doneResult.done,
      detail: doneResult.gates.filter(g => !g.pass).map(g => `${g.id} ${g.label}`).join(', ') || 'all gates pass',
    });
  }

  return { pass: checks.every(c => c.pass), checks };
}

export function formatGateOutput(result: GateResult): string {
  const lines: string[] = [];
  lines.push(result.pass ? 'BATON GATE: PASS' : 'BATON GATE: FAIL');
  for (const c of result.checks) {
    lines.push(`  [${c.pass ? 'PASS' : 'FAIL'}] ${c.name.padEnd(10)} ${c.detail}`);
  }
  return lines.join('\n');
}

// ---------- GitHub Action bootstrap ----------

export const GATE_WORKFLOW = `# Generated by baton gate --init. Stage 5 Reach.
# Fails the PR if the Baton ledger is structurally broken, claims went stale,
# or conflicts are unacknowledged.
name: Baton Gate

on:
  pull_request:
  push:
    branches: [main]

jobs:
  baton-gate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Install baton
        run: npm install -g github:isaJrKai/baton#v1.3.0
      - name: Baton gate
        run: baton gate
`;

export async function gateInit(repoRoot: string): Promise<{ path: string; created: boolean }> {
  const workflowPath = path.join(repoRoot, '.github/workflows/baton-gate.yml');
  let created = true;
  try {
    const { readFile } = await import('node:fs/promises');
    await readFile(workflowPath, 'utf8');
    created = false; // already exists — never overwrite user edits
  } catch {
    await mkdir(path.dirname(workflowPath), { recursive: true });
    await writeFile(workflowPath, GATE_WORKFLOW, 'utf8');
  }
  return { path: '.github/workflows/baton-gate.yml', created };
}
